#!/bin/bash
# Tear down the Azure side of the demo environment for "Practical AI Integration".
#
# Deletes the ENTIRE resource group created by setup.sh, including the Azure
# OpenAI resource and every model deployment. This cannot be undone.
#
# The deployments are pay-per-token, so an idle environment costs little. Tear
# it down anyway: a forgotten demo environment is a line item nobody notices
# until it has run for a year.
#
# Usage:
#   ./infra/teardown.sh
#   AOAI_RESOURCE_GROUP=rg-something-else ./infra/teardown.sh

set -euo pipefail

RESOURCE_GROUP="${AOAI_RESOURCE_GROUP:-rg-practical-ai}"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$REPO_ROOT/code/.env"

if ! command -v az > /dev/null 2>&1; then
    echo "ERROR: Azure CLI not found."
    exit 1
fi

if ! az account show > /dev/null 2>&1; then
    echo "ERROR: Not signed in. Run: az login"
    exit 1
fi

if [ "$(az group exists --name "$RESOURCE_GROUP")" != "true" ]; then
    echo "Resource group '$RESOURCE_GROUP' does not exist. Nothing to do."
    exit 0
fi

SUBSCRIPTION=$(az account show --query name --output tsv)

echo ""
echo "About to DELETE this resource group and everything in it."
echo ""
echo "  Subscription:   $SUBSCRIPTION"
echo "  Resource group: $RESOURCE_GROUP"
echo ""
echo "Contents:"
az resource list --resource-group "$RESOURCE_GROUP" \
    --query "[].{Name:name, Type:type}" --output table 2>/dev/null || echo "  (unable to list)"
echo ""
echo "This cannot be undone."
echo ""

printf 'Type the resource group name to confirm: '
read -r CONFIRM

if [ "$CONFIRM" != "$RESOURCE_GROUP" ]; then
    echo "Input did not match. Nothing deleted."
    exit 1
fi

echo ""
echo "Deleting '$RESOURCE_GROUP'..."
az group delete --name "$RESOURCE_GROUP" --yes --no-wait

echo "Deletion started in the background. Check with:"
echo "    az group exists --name $RESOURCE_GROUP"

# The generated .env now points at resources that are going away. Leaving it in
# place makes the next run fail confusingly.
if [ -f "$ENV_FILE" ] && grep -q 'Generated by infra/setup.sh' "$ENV_FILE" 2>/dev/null; then
    mv "$ENV_FILE" "$ENV_FILE.stale"
    echo ""
    echo "Moved the generated code/.env to code/.env.stale (it points at deleted resources)."
    echo "To keep working locally: cp code/.env.example code/.env and set LLM_PROVIDER=ollama."
fi
